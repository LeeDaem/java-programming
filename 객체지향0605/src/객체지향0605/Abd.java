package 객체지향0605;

public class Abd {
	private int a;
	private int b;
	private double c;
	
	// 필드값을 설정하거나 얻어오는 메소드 : setter, getter
	// getter
	public int getA() {
		return a;
	}
	
	// setter
	private void setA(int a) {
		this.a = a;
	}

	public int getB() {
		return b;
	}

	public void setB(int b) {
		this.b = b;
	}

	public double getC() {
		return c;
	}

	public void setC(double c) {
		this.c = c;
	}
	
	
}